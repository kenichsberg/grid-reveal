#!/usr/bin/env bash
# Regenerates the TypeScript API contract from the Rust DTOs.
#
# ts-rs emits one declaration per `#[ts(export)]` type via generated tests, so
# the export runs as a test pass. Run this after changing anything in
# apps/api/src/dto.rs.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out_dir="$repo_root/apps/web/src/lib/api/types"

rm -rf "$out_dir"
mkdir -p "$out_dir"

cd "$repo_root/apps/api"
TS_RS_EXPORT_DIR="$out_dir" cargo test export_bindings --quiet

# Barrel file so the app can `import type { ScreenDetail } from '$lib/api/types'`.
{
  echo "// Generated by scripts/gen-types.sh. Do not edit."
  for f in "$out_dir"/*.ts; do
    name="$(basename "$f" .ts)"
    [ "$name" = "index" ] && continue
    echo "export type { $name } from './$name';"
  done
} > "$out_dir/index.ts"

echo "Wrote $(ls -1 "$out_dir"/*.ts | wc -l | tr -d ' ') files to $out_dir"
